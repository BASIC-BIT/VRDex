import assert from "node:assert/strict";
import { test } from "node:test";
import { setTimeout as delay } from "node:timers/promises";
import { createLeaseWatchdog } from "../src/worker/lease";
import { OwnershipLeaseSchema } from "../src/contracts";
const lease = OwnershipLeaseSchema.parse({ streamKey: "vrcdn/Alpha/1", workerId: "one", epoch: 1, serverNow: 100000, expiresAt: 130000, renewAfterMs: 10000 });
test("send-time authority expires conservatively and cannot revive after delayed renewal", () => {
    let now = 1000;
    let fences = 0;
    const w = createLeaseWatchdog({ clock: () => now, fence: () => { fences++; } });
    assert.equal(w.accept(lease, 0), true);
    now = 29749;
    assert.equal(w.check(), true);
    now = 29750;
    assert.equal(w.check(), false);
    assert.equal(fences, 1);
    assert.equal(w.accept(lease, 29000), false);
    w.stop();
    assert.equal(fences, 1);
});
test("independent interval fences synchronously while renewal and cleanup promises stall", async () => {
    let now = 0;
    let publishing = true;
    let cleanupDone = false;
    const pending = new Promise<void>(() => { });
    const w = createLeaseWatchdog({ clock: () => now, fence: () => { publishing = false; void pending.then(() => { cleanupDone = true; }); } });
    w.accept(lease, 0);
    void pending.then(() => w.accept(lease, 10000));
    now = 30000;
    await delay(350);
    assert.equal(publishing, false);
    assert.equal(cleanupDone, false);
    w.stop();
});
test("rejects late initial response, wrong identity, out-of-order replies and clock rollback", () => {
    let now = 30000;
    let fences = 0;
    const w = createLeaseWatchdog({ clock: () => now, fence: () => { fences++; } });
    assert.equal(w.accept(lease, 0), false);
    assert.equal(fences, 1);
    const other = createLeaseWatchdog({ clock: () => now, fence: () => { } });
    assert.equal(other.accept(lease, 30000), true);
    now = 31000;
    assert.equal(other.accept(lease, 29000), false);
    assert.equal(other.accept({ ...lease, epoch: 2 }, 31000), false);
    now = 29999;
    assert.equal(other.check(), false);
    other.stop();
    w.stop();
});
test("no local authority exists before a lease is accepted; valid renewal extends only from send time", () => {
    let now = 0;
    const w = createLeaseWatchdog({ clock: () => now, fence: () => { } });
    assert.equal(w.check(), false);
    assert.equal(w.accept(lease, 0), true);
    now = 15000;
    assert.equal(w.accept({ ...lease, serverNow: 110000, expiresAt: 140000 }, 10000), true);
    now = 39749;
    assert.equal(w.check(), true);
    now = 39750;
    assert.equal(w.check(), false);
    w.stop();
});
